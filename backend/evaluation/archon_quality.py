import json
from pathlib import Path

from deepeval import evaluate
from deepeval.metrics import GEval
from deepeval.test_case import LLMTestCase, SingleTurnParams

from evaluation.judge import judge


# ============================================================
# FILE PATHS
# ============================================================

DATASET_PATH = Path(
    "evaluation/datasets/archon_golden.jsonl"
)

RUN_PATH = Path(
    "evaluation/results/run_20260904_034744.json"
)

RESULTS_PATH = Path(
    "evaluation/results/archon_quality_results.json"
)


# ============================================================
# LOAD DATASET
# ============================================================

def load_dataset():

    cases = []

    with DATASET_PATH.open(
        "r",
        encoding="utf-8"
    ) as f:

        for line in f:

            if line.strip():

                cases.append(
                    json.loads(line)
                )

    return cases




def load_run():

    with RUN_PATH.open(
        "r",
        encoding="utf-8"
    ) as f:

        return json.load(f)




def find_result(run, case_id):

    for result in run["results"]:

        if result["id"] == case_id:

            return result

    raise ValueError(
        f"Run result not found: {case_id}"
    )




SCORING_SCALE = """
Use this scoring scale:

1.0 = Exceptional.
      Fully satisfies the evaluation criteria with strong
      technical depth, excellent consistency, and no
      meaningful omissions.

0.8 = Strong.
      Clearly satisfies the criteria with only minor
      weaknesses or omissions.

0.6 = Adequate.
      Satisfies the main requirements but has noticeable
      gaps, limited justification, or areas needing improvement.

0.4 = Weak.
      Partially satisfies the criteria but contains significant
      omissions, questionable decisions, or insufficient detail.

0.2 = Very weak.
      Only superficial coverage or major technical problems.

0.0 = Fails.
      The architecture fundamentally fails to address the
      requirements or contains serious technical problems.

IMPORTANT:

Do not give 1.0 simply because something is mentioned.

Do not reward length, formatting, or the number of technologies.

Do not reward unnecessary complexity.

Evaluate the actual technical quality of the architecture.

Consider all five evaluation dimensions when assigning the
overall score.
"""




def create_quality_metric(golden_case):

    user_goal = golden_case["user_goal"]

    must_address = json.dumps(
        golden_case["must_address"],
        indent=2
    )

    quality_criteria = json.dumps(
        golden_case["quality_criteria"],
        indent=2
    )

    return GEval(

        name="Archon Overall Quality",

        criteria=f"""
Evaluate the overall quality of the architecture blueprint
generated by Archon.

USER GOAL:

{user_goal}


REQUIREMENTS THAT MUST BE ADDRESSED:

{must_address}


GOLDEN QUALITY CRITERIA:

{quality_criteria}


Evaluate the blueprint across these five dimensions:


1. REQUIREMENTS COVERAGE

Determine whether the important requirements are addressed
and whether the architecture actually explains how those
requirements are satisfied.

Evaluate:

- coverage of important requirements
- connection between requirements and architectural decisions
- missing or contradictory requirements
- sufficient detail to demonstrate that requirements were
  actually considered

Do not award a high score merely because requirements are
mentioned.


2. ARCHITECTURE QUALITY

Evaluate:

- appropriateness of the architecture style
- separation of responsibilities
- component interactions
- data flow
- scalability
- reliability
- fault tolerance
- avoidance of unnecessary complexity
- consistency with the user's requirements

The components should form a coherent architecture rather
than simply being a list of components.


3. TECHNOLOGY DECISIONS

Evaluate:

- whether technologies fit the requirements
- whether major choices have meaningful justification
- whether choices are consistent with the architecture
- whether important trade-offs are considered
- whether unnecessary technologies are avoided
- whether the technology stack is coherent

Do not reward technologies simply because they are popular.


4. RELIABILITY AND SECURITY

Evaluate the relevant aspects of:

- authentication and authorization
- data protection
- privacy
- secrets management
- failure handling
- retries and timeouts
- recovery
- scalability and resilience
- monitoring and observability
- backup and disaster recovery

Judge these according to the actual risks and requirements
of the user's system.

Do not require irrelevant security mechanisms.


5. FINAL BLUEPRINT QUALITY

Evaluate whether the final blueprint:

- is clear and well organized
- contains sufficient technical detail
- provides a coherent end-to-end design
- is internally consistent
- explains important architectural decisions
- identifies assumptions or open decisions where appropriate
- could realistically serve as a starting point for implementation
- avoids unnecessary verbosity and irrelevant information


OVERALL JUDGMENT:

Consider all five dimensions together when assigning the
single overall score.

A strong architecture should not receive a high score if it
has a serious weakness in an important dimension.

Likewise, a minor weakness should not cause an otherwise
excellent architecture to receive a very low score.

The final score represents the overall quality of the
architecture across all five dimensions.

{SCORING_SCALE}
""",

        evaluation_params=[
            SingleTurnParams.INPUT,
            SingleTurnParams.ACTUAL_OUTPUT,
        ],

        threshold=0.5,

        model=judge,
    )




def evaluate_case(golden_case, run_result):

    archon_output = run_result["result"]

    final_blueprint = archon_output.get(
        "final_blueprint"
    )



    if not final_blueprint:

        return {
            "id": golden_case["id"],
            "category": golden_case["category"],
            "status": "incomplete",
            "score": None,
            "overall_score": 0.0,
            "reason": "No final blueprint was produced.",
        }



    test_case = LLMTestCase(

        input=golden_case["user_goal"],

        actual_output=final_blueprint,
    )




    metric = create_quality_metric(
        golden_case
    )


    print(
        "\n    → Archon Overall Quality"
    )



    try:

        result = evaluate(

            test_cases=[
                test_case
            ],

            metrics=[
                metric
            ],
        )


        metric_result = (
            result
            .test_results[0]
            .metrics_data[0]
        )


        score = metric_result.score


        if score is not None:

            print(
                f"      Score: {score:.2f}"
            )

        else:

            print(
                "      Score: unavailable"
            )


        return {

            "id": golden_case["id"],

            "category": golden_case["category"],

            "status": "evaluated",

            "score": score,

            "overall_score": score or 0.0,

            "success": metric_result.success,

            "reason": metric_result.reason,
        }


    except Exception as error:

        print(
            f"      ERROR: {error}"
        )


        return {

            "id": golden_case["id"],

            "category": golden_case["category"],

            "status": "evaluation_error",

            "score": None,

            "overall_score": 0.0,

            "error": str(error),
        }




def main():

    dataset = load_dataset()

    run = load_run()


    print(
        f"Loaded {len(dataset)} golden cases"
    )

    print(
        "Judge: Groq GPT-OSS-120B"
    )

    print(
        "Metrics per case: 1"
    )

    print(
        f"Total metric evaluations: "
        f"{len(dataset)}"
    )


    results = []




    for case_number, golden_case in enumerate(
        dataset,
        start=1
    ):

        case_id = golden_case["id"]


        print(
            "\n" + "=" * 60
        )

        print(
            f"CASE {case_number}/{len(dataset)}"
        )

        print(
            f"{case_id}: "
            f"{golden_case['category']}"
        )

        print(
            "=" * 60
        )


        try:

            run_result = find_result(
                run,
                case_id
            )


            result = evaluate_case(
                golden_case,
                run_result
            )


            results.append(
                result
            )


            print(
                f"\n    Overall: "
                f"{result['overall_score']:.2f}"
            )


        except Exception as error:

            print(
                f"\n    CASE ERROR: {error}"
            )


            results.append({

                "id": case_id,

                "category": golden_case["category"],

                "status": "error",

                "score": None,

                "overall_score": 0.0,

                "error": str(error),
            })




    output = {

        "run_id": run["run_id"],

        "evaluation_type": "DeepEval GEval",

        "judge_model": "Groq GPT-OSS-120B",

        "total_cases": len(results),

        "metrics_per_case": 1,

        "total_metrics": len(results),

        "evaluation_dimensions": [

            "Requirements Coverage",

            "Architecture Quality",

            "Technology Decisions",

            "Reliability and Security",

            "Final Blueprint Quality",
        ],

        "results": results,
    }




    RESULTS_PATH.parent.mkdir(
        parents=True,
        exist_ok=True
    )


    with RESULTS_PATH.open(
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            output,
            f,
            indent=2,
            ensure_ascii=False
        )



    print(
        "\n" + "=" * 70
    )

    print(
        "ARCHON QUALITY EVALUATION COMPLETE"
    )

    print(
        "=" * 70
    )


    evaluated_scores = []


    for result in results:

        if result["status"] == "evaluated":

            score = result["overall_score"]

            if score is not None:

                evaluated_scores.append(
                    score
                )

        else:

            score = result["overall_score"]


        print(

            f"{result['id']:15} | "
            f"{result['category']:25} | "
            f"{result['status']:20} | "
            f"{score:.2f}"

        )




    if evaluated_scores:

        global_score = (
            sum(evaluated_scores)
            / len(evaluated_scores)
        )

    else:

        global_score = 0.0


    print(
        "\n" + "-" * 70
    )

    print(
        f"GLOBAL QUALITY SCORE: "
        f"{global_score:.2f}"
    )

    print(
        f"GLOBAL QUALITY PERCENTAGE: "
        f"{global_score * 100:.1f}%"
    )

    print(
        "-" * 70
    )


    print(
        "\nResults saved to:"
    )

    print(
        RESULTS_PATH
    )



if __name__ == "__main__":

    main()